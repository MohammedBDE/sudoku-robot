"""
The digit "database": how the robot writes each of the digits 1-9, as plain data.

The shapes themselves are defined in `digit_strokes.py` (that is what the
writer uses at run time). This module turns them into a readable JSON file,
`teach_data/digits.json`, and a picture, `calib/digits_sheet.png`, so the
shapes can be inspected, shown and checked without reading code:

    python scripts/export_digits.py

`tests/test_digit_database.py` fails if the JSON on disk ever differs from
what the code produces, so the file cannot silently go stale.

Every digit is drawn on a unit square with six anchor points (the corners
and the middle of the left and right sides, as on a seven-segment display):

        TL --------- TR          (0,1) ... (1,1)
        |            |
        ML --------- MR          (0,.5) .. (1,.5)
        |            |
        BL --------- BR          (0,0) ... (1,0)

and is traced as ONE continuous pen-down path through those points.
"""
import json
import os
from typing import Dict, List

from .. import config
from .digit_strokes import _DIGIT_SEGMENTS, _SEGMENTS, DIGIT_PATHS
from .pen_writer import DEFAULT_FILL_RATIO

DIGITS_JSON_PATH = os.path.join(config.TEACH_DATA_DIR, "digits.json")
DIGITS_SHEET_PATH = os.path.join(config.CALIB_DIR, "digits_sheet.png")

#: unit-square coordinates -> anchor name
ANCHORS = {(0.0, 1.0): "TL", (1.0, 1.0): "TR", (0.0, 0.5): "ML", (1.0, 0.5): "MR", (0.0, 0.0): "BL", (1.0, 0.0): "BR"}
#: unordered pair of anchors -> seven-segment name
_SEGMENT_BY_ENDPOINTS = {frozenset((ANCHORS[a], ANCHORS[b])): name for name, (a, b) in _SEGMENTS.items()}


def _walk(digit: int) -> Dict[str, object]:
    path = DIGIT_PATHS[digit]
    names = [ANCHORS[p] for p in path]
    walked: List[str] = [_SEGMENT_BY_ENDPOINTS[frozenset(pair)] for pair in zip(names, names[1:])]
    retraced = sorted({s for s in walked if walked.count(s) > 1})
    return {
        "segments": list(_DIGIT_SEGMENTS[digit]),
        "path": names,
        "line_count": len(walked),
        "retraced_segments": retraced,
        # digit mode: travel (pen up), pen down, one move per further point, pen up.
        "pen_moves": len(path) + 2,
    }


def build_database() -> Dict[str, object]:
    size_mm = config.CELL_SIZE_MM * DEFAULT_FILL_RATIO
    return {
        "_about": "How the robot writes each digit 1-9. Generated by scripts/export_digits.py "
                  "from sudoku_robot/writer/digit_strokes.py; a test keeps the two in sync.",
        "style": "seven-segment, straight lines only, one continuous pen-down path per digit",
        "coordinates": "unit square: u to the right (0..1), v up (0..1), as printed on the paper",
        "anchor_points": {name: list(uv) for uv, name in ANCHORS.items()},
        "cell_size_mm": config.CELL_SIZE_MM,
        "fill_ratio": DEFAULT_FILL_RATIO,
        "digit_size_mm": size_mm,
        "digits": {str(d): _walk(d) for d in sorted(DIGIT_PATHS)},
    }


def format_database(db: Dict[str, object]) -> str:
    """JSON with short lists kept on one line, so each digit reads as a single record."""
    out = ["{"]
    head = [k for k in db if k != "digits"]
    for key in head:
        out.append(f"  {json.dumps(key)}: {json.dumps(db[key], ensure_ascii=False)},")
    out.append('  "digits": {')
    digits = db["digits"]
    for i, (d, rec) in enumerate(digits.items()):
        out.append(f'    "{d}": {{')
        fields = list(rec.items())
        for j, (k, v) in enumerate(fields):
            comma = "," if j < len(fields) - 1 else ""
            out.append(f"      {json.dumps(k)}: {json.dumps(v)}{comma}")
        out.append("    }" + ("," if i < len(digits) - 1 else ""))
    out.append("  }")
    out.append("}")
    return "\n".join(out) + "\n"


def save_database(path: str = DIGITS_JSON_PATH) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(format_database(build_database()))
    return path


def render_sheet(path: str = DIGITS_SHEET_PATH) -> str:
    """A 3x3 picture: each digit's path through the six anchor points, in drawing order."""
    from PIL import Image, ImageDraw

    from ..fonts import load_font

    tile, pad = 300, 40
    cols = 3
    W = cols * tile + 2 * pad
    H = 3 * tile + 2 * pad + 70
    img = Image.new("RGB", (W, H), "white")
    d = ImageDraw.Draw(img)
    title_font, label_font = load_font(34, bold=True), load_font(26, bold=True)
    small_font, note_font = load_font(18), load_font(15)
    d.text((W // 2, 30), "Digit strokes: one continuous pen-down path per digit", font=title_font,
           fill="#1f2937", anchor="mm")
    colors = ["#2563eb", "#7c3aed", "#059669", "#d97706", "#dc2626", "#0891b2", "#be185d", "#4d7c0f", "#475569"]

    for i, digit in enumerate(sorted(DIGIT_PATHS)):
        r, c = divmod(i, cols)
        x0, y0 = pad + c * tile, 70 + pad + r * tile
        bw, bh = 120, 160           # box that the unit square is drawn into
        bx, by = x0 + (tile - bw) // 2, y0 + 55

        def pt(p):
            return bx + p[0] * bw, by + (1 - p[1]) * bh

        d.text((x0 + tile // 2, y0 + 20), f"Digit {digit}", font=label_font, fill="#1f2937", anchor="mm")
        d.rectangle((bx, by, bx + bw, by + bh), outline="#e5e7eb", width=2)
        for uv, name in ANCHORS.items():
            x, y = pt(uv)
            d.ellipse((x - 4, y - 4, x + 4, y + 4), fill="#cbd5e1")
            if uv[0] == 0:
                d.text((x - 24, y), name, font=small_font, fill="#94a3b8", anchor="rm")
            else:
                d.text((x + 24, y), name, font=small_font, fill="#94a3b8", anchor="lm")
        points = DIGIT_PATHS[digit]
        col = colors[i % len(colors)]
        d.line([pt(p) for p in points], fill=col, width=5, joint="curve")
        visits: Dict[tuple, List[str]] = {}
        for n, p in enumerate(points, start=1):
            visits.setdefault(p, []).append(str(n))      # a point can be visited twice (3, 4, 6, 8, 9)
        for p, nums in visits.items():
            x, y = pt(p)
            half = 11 if len(nums) == 1 else 19
            d.rounded_rectangle((x - half, y - 11, x + half, y + 11), 11, fill=col)
            d.text((x, y), ",".join(nums), font=small_font, fill="white", anchor="mm")
        rec = _walk(digit)
        note = f"{rec['line_count']} lines, {rec['pen_moves']} pen moves"
        if rec["retraced_segments"]:
            note += f", retraces {', '.join(rec['retraced_segments'])}"
        d.text((x0 + tile // 2, by + bh + 38), note, font=note_font, fill="#475569", anchor="mm")

    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)
    return path
